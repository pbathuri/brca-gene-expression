# Real count-based analysis. Contrast is tumor minus normal, controlling for patient.
suppressPackageStartupMessages(library(DESeq2))
args <- commandArgs(trailingOnly=TRUE)
if (length(args) < 2) stop("Usage: Rscript scripts/deseq2.R INPUT_DIR OUTPUT_DIR [min_count]")
in_dir <- args[1]; out <- args[2]; dir.create(out, recursive=TRUE, showWarnings=FALSE)
min_count <- if (length(args)>=3) as.numeric(args[3]) else 10
counts <- as.matrix(read.csv(file.path(in_dir,"counts.csv"), row.names=1, check.names=FALSE))
meta <- read.csv(file.path(in_dir,"samples.csv"), row.names=1, check.names=FALSE)
stopifnot(identical(colnames(counts),rownames(meta)),!anyDuplicated(rownames(counts)))
stopifnot(all(is.finite(counts)),all(counts>=0),all(counts==floor(counts)))
meta$condition <- factor(meta$condition,levels=c("normal","tumor"))
meta$patient <- factor(meta$patient)
stopifnot(!anyNA(meta$condition),all(table(meta$patient,meta$condition)==1))
model <- model.matrix(~ patient + condition, data=meta)
stopifnot(qr(model)$rank==ncol(model))
write.csv(model,file.path(out,"design_matrix.csv"))
dds <- DESeqDataSetFromMatrix(countData=counts,colData=meta,design=~ patient + condition)
keep <- rowSums(counts(dds)>=min_count)>=nlevels(meta$patient)
write.csv(data.frame(gene_id=rownames(dds),retained=keep),file.path(out,"gene_filter.csv"),row.names=FALSE)
dds <- dds[keep,]
if(nrow(dds)<10) stop("Too few retained genes")
dds <- DESeq(dds)
res <- results(dds,contrast=c("condition","tumor","normal"),alpha=0.05)
tab <- data.frame(gene_id=rownames(res),as.data.frame(res),check.names=FALSE)
genes <- read.csv(file.path(in_dir,"genes.csv"),check.names=FALSE)
tab <- merge(tab,genes,by="gene_id",all.x=TRUE,sort=FALSE)
tab$method <- "DESeq2: ~ patient + condition; tumor vs normal"
write.csv(tab,file.path(out,"differential_expression.csv"),row.names=FALSE)
write.csv(counts(dds,normalized=TRUE),file.path(out,"normalized_counts.csv"))
# Full VST works even when the quick vst() shortcut has too few high-count genes.
vsd <- varianceStabilizingTransformation(dds,blind=FALSE)
write.csv(assay(vsd),file.path(out,"vst.csv"))
pdf(file.path(out,"vst_qc.pdf"),width=7,height=6)
print(plotPCA(vsd,intgroup="condition"))
heatmap(as.matrix(dist(t(assay(vsd)))),symm=TRUE,main="Sample distances: VST")
dev.off()
writeLines(capture.output(sessionInfo()),file.path(out,"R_sessionInfo.txt"))
saveRDS(dds,file.path(out,"dds.rds"))
cat("Retained genes:",sum(keep),"\nContrast: tumor vs normal\n")
